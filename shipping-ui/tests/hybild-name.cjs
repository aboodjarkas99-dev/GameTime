const fs=require('node:fs'),assert=require('node:assert/strict'),ts=require('typescript');
require.extensions['.ts']=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const {productLabel}=require('../src/lib/pallet/plan.ts');
assert.equal(productLabel('GTHS-5','Hybild','gal5'),'Hybild Sealer');
assert.equal(productLabel('GTHS-5','Hybild Sealer','gal5'),'Hybild Sealer');
assert.notEqual(productLabel('GTHS-5','Hybild Tinted Sealer','gal5'),'Hybild Sealer');
console.log('Hybild resolves to Hybild Sealer; tinted products remain distinct.');
const {canonicalProductName}=require('../src/lib/pallet/product-names.ts');
assert.equal(productLabel('TEST','OverTime','gal5'),'OverTime Finish');
assert.equal(productLabel('TEST','OverTime Catalyst','quart'),'OverTime Catalyst');
assert.equal(productLabel('TEST','Xcel A','gal5'),'X-cel 2k High Solids Part A');
assert.equal(productLabel('TEST','Xcel B','gal1'),'X-cel Catalyst Part B');
assert.equal(productLabel('TEST','X-cel Catalyst Part B','gal1'),'X-cel Catalyst Part B');
assert.equal(canonicalProductName('Xcel Part B'),'X-cel Catalyst Part B');
assert.equal(canonicalProductName('OverTime Catalyst'),'OverTime Catalyst');
console.log('OverTime Finish, X-cel A/B and inventory mappings resolve correctly; catalyst stays separate.');
assert.equal(productLabel('TEST','1K','gal5'),'AND1k');
assert.equal(productLabel('TEST','AND1k','gal5'),'AND1k');
assert.equal(canonicalProductName('1K'),'AND1k');
